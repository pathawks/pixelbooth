#!/bin/zsh
# Make the vendored header search paths inside SwiftPM's generated response
# files absolute, by copying pinned headers into the shim target's own
# public headers directory (this avoids any working-directory dependency).
set -euo pipefail
cd "$(dirname "$0")/.."

# This is a C/Objective-C target. SwiftPM scans its public include directory;
# staging the optional C++ wrapper would make its umbrella module require C++.
AVIF_C_HEADER="vendor/build/avif-install/include/avif/avif.h"
SHIM_AVIF_HEADERS="Tools/PixelBoothCAvif/include/avif"
if [[ ! -f "$AVIF_C_HEADER" ]]; then
  print -u2 "Pinned libavif C header missing; run scripts/fetch_deps.sh first."
  exit 1
fi
mkdir -p "$SHIM_AVIF_HEADERS"
if ! cmp -s "$AVIF_C_HEADER" "$SHIM_AVIF_HEADERS/avif.h"; then
  cp "$AVIF_C_HEADER" "$SHIM_AVIF_HEADERS/avif.h"
fi
# Remove only the wrapper generated by older versions of this staging script.
rm -f "$SHIM_AVIF_HEADERS/avif_cxx.h"
echo "Pinned libavif C header staged."
